sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "sigmafork" / "scripts"))
import sigmafork as sf  # noqa: E402


def quiet(fn, *args):
    with redirect_stdout(io.StringIO()):
        return fn(*args)


class Spellings(unittest.TestCase):
    def test_windows_root_has_every_spelling(self):
        got = dict(sf.spellings(r"C:\AI\Repo"))
        self.assertEqual(got["back"], r"C:\AI\Repo")
        self.assertEqual(got["fwd"], "C:/AI/Repo")
        self.assertEqual(got["escaped"], "C:" + "\\\\" + "AI" + "\\\\" + "Repo")
        self.assertEqual(got["gitbash"], "/c/AI/Repo")
        self.assertEqual(got["wsl"], "/mnt/c/AI/Repo")
        self.assertEqual(got["file"], "file:///C:/AI/Repo")

    def test_rewrite_keeps_the_style_and_stops_at_a_name_boundary(self):
        rx, styles = sf.pattern(r"C:\AI\Repo")
        text = rb"a C:\AI\Repo\x b c:/ai/repo/y c C:\AI\Repo_old d C:\AI\Repo.bak e /c/AI/Repo."
        out = rx.sub(lambda m: sf.render(r"D:\T\Copy", styles[m.group(0).decode().lower()]).encode(), text)
        self.assertEqual(out, rb"a D:\T\Copy\x b D:/T/Copy/y c C:\AI\Repo_old d C:\AI\Repo.bak e /d/T/Copy.")

    def test_posix_destination(self):
        self.assertEqual(sf.render("/home/me/copy", "back"), "/home/me/copy")
        self.assertEqual(sf.render("/home/me/copy", "file"), "file:///home/me/copy")


class EndToEnd(unittest.TestCase):
    def test_selftest_passes(self):
        self.assertEqual(quiet(sf.cmd_selftest), 0)

    def test_git_remote_into_the_source_blocks_verify(self):
        with tempfile.TemporaryDirectory() as tmp:
            src, dest = Path(tmp, "Src"), Path(tmp, "Dest")
            (src / ".git").mkdir(parents=True)
            (src / ".git" / "config").write_text(f'[remote "origin"]\n\turl = {src}\n', encoding="utf-8")
            (src / "a.txt").write_text("plain", encoding="utf-8")
            self.assertEqual(quiet(sf.cmd_copy, src, dest, [], False, False), 0)
            self.assertEqual(quiet(sf.cmd_fix, dest, str(src), []), 0)
            self.assertEqual(quiet(sf.cmd_verify, dest, str(src)), 1, "a remote into the source must block")
            (dest / ".git" / "config").write_text('[remote "origin"]\n\turl = https://example.invalid/x.git\n', encoding="utf-8")
            self.assertEqual(quiet(sf.cmd_verify, dest, str(src)), 0)

    def test_map_rewrites_an_outside_folder(self):
        with tempfile.TemporaryDirectory() as tmp:
            src, dest = Path(tmp, "Src"), Path(tmp, "Dest")
            src.mkdir()
            esc = "\\\\"  # two backslashes, as JSON writes one
            (src / "cfg.json").write_text('{"out": "Z:' + esc + 'renders' + esc + 'Src' + esc + 'final"}', encoding="utf-8")
            quiet(sf.cmd_copy, src, dest, [], False, False)
            report = sf.scan(dest, str(src), [])
            self.assertTrue(any(k.startswith("Z:\\renders\\Src") for k in report["outside_paths"]), report)
            quiet(sf.cmd_fix, dest, str(src), [("Z:\\renders\\Src", "Z:\\renders\\Copy")])
            self.assertIn("Z:" + esc + "renders" + esc + "Copy" + esc + "final", (dest / "cfg.json").read_text(encoding="utf-8"))
            self.assertIn("Src", (src / "cfg.json").read_text(encoding="utf-8"))


class StatsAndGuide(unittest.TestCase):
    def make_repo(self, root: Path):
        (root / "src").mkdir(parents=True)
        (root / "src" / "app.py").write_text("# a comment\n\nimport os\nprint(os.name)\n", encoding="utf-8")
        (root / "src" / "ui.js").write_text("/* block\n still comment */\nconst a = 1; // tail\n// only comment\nexport { a };\n", encoding="utf-8")
        (root / "README.md").write_text("# Title\n\nOne line.\n", encoding="utf-8")
        (root / "package-lock.json").write_text('{\n"x": 1\n}\n', encoding="utf-8")
        (root / "gen.py").write_text("# @generated by a tool\nx = 1\n", encoding="utf-8")
        for skip in ("node_modules/pkg", "build", "dist", ".venv"):
            (root / skip).mkdir(parents=True)
            (root / skip / "big.js").write_text("var x = 1;\n" * 50, encoding="utf-8")
        (root / "env2").mkdir()
        (root / "env2" / "pyvenv.cfg").write_text("home = x\n", encoding="utf-8")
        (root / "env2" / "site.py").write_text("x = 1\n", encoding="utf-8")

    def test_stats_count_real_code_and_leave_out_scaffolding(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp, "Repo")
            self.make_repo(root)
            s = sf.stats(root)
            self.assertEqual(s["code"], 4, s)  # app.py 2 + ui.js 2; comments, blanks, lock and generated files out
            self.assertEqual(s["comments"], 4, s)
            self.assertEqual(s["docs"], 2, s)
            self.assertEqual(s["generated"], 2, s)
            self.assertEqual(s["folders"], 1, s)  # only src/
            for k in ("node_modules", "build", "dist", ".venv", "venv"):
                self.assertIn(k, s["left_out"], s["left_out"])
            self.assertEqual({lang["name"] for lang in s["langs"]}, {"Python", "JavaScript"})
            self.assertEqual(s["tree"]["k"][0]["n"], "src")

    def test_guide_writes_data_and_check_lists_what_is_left(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp, "Repo")
            self.make_repo(root)
            self.assertEqual(quiet(sf.cmd_guide, root, None, None, False, []), 0)
            page = root / "ONBOARDING.html"
            html = page.read_text(encoding="utf-8")
            data = json.loads(sf.DATA_RX.search(html).group(2))
            self.assertEqual(data["stats"]["code"], 4)
            self.assertEqual(data["stats"]["files"], 5, "the course does not count itself")
            blocking, _ = sf.guide_check(html)
            self.assertTrue(any("FILL" in b for b in blocking))
            self.assertFalse(any("no repo data" in b for b in blocking))
            self.assertEqual(quiet(sf.cmd_guide, root, None, None, True, []), 1)
            page.write_text(html.replace("FILL", "Done"), encoding="utf-8")
            quiet(sf.cmd_guide, root, None, None, False, [])  # a second run replaces only the data block
            again = page.read_text(encoding="utf-8")
            self.assertNotIn("FILL", again)
            self.assertEqual(sf.guide_check(again)[0], [])

    def test_guide_check_flags_long_paragraphs_and_chip_soup(self):
        long_p = "<p>" + " ".join(["Word."] * 5) + "</p>"
        chips = "<p>Run <code>a</code> then <code>b</code> then <code>c</code> then <code>d</code>.</p>"
        term = '<span class="term">Board</span>'
        html = '<script type="application/json" id="sigmafork-data">{}</script>' + long_p + chips + term
        text = "\n".join(sf.guide_check(html)[1])
        self.assertIn("5 sentences", text)
        self.assertIn("inline code chips", text)
        self.assertIn("term without data-def", text)
        self.assertIn("figures", text)


if __name__ == "__main__":
    unittest.main()
