TEXT_KINDS = {"code", "docs", "data"}


def _files(root: Path, extra=()):
    """(relative posix path, kind, bytes) of every owned text file under 5 MB; scaffolding and generated files left out."""
    for dirpath, dirnames, filenames in os.walk(root):
        here = Path(dirpath)
        dirnames[:] = sorted(d for d in dirnames if not _is_link(here / d) and not _is_scaffold_dir(here / d, d, extra))
        for name in filenames:
            p = here / name
            lang = _lang(name)
            if name in NOISE or _is_link(p):
                continue
            rel = p.relative_to(root).as_posix()
            if not lang and not name.lower().startswith((".env", "readme", "license", "licence")):
                yield rel, "other", b""
                continue
            try:
                if p.stat().st_size > MAX_SCAN_BYTES:
                    continue
                data = p.read_bytes()
            except OSError:
                continue
            if b"\0" in data[:8192] or _is_generated(name, data):
                continue
            yield rel, (lang[1] if lang else "docs"), data


