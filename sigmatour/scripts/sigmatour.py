def _git(root: Path, *args) -> str:
    try:
        r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, timeout=60,
                           encoding="utf-8", errors="replace")
        return r.stdout if r.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def history(root: Path) -> dict:
    log = _git(root, "log", "--format=%at|%an", "--no-merges")
    if not log.strip():
        return {}
    rows = [l.split("|", 1) for l in log.splitlines() if "|" in l]
    times = [int(t) for t, _ in rows if t.isdigit()]
    people = {}
    for _, name in rows:
        people[name] = people.get(name, 0) + 1
    remote = _git(root, "remote", "get-url", "origin").strip()
    remote = re.sub(r"//[^@/]+@", "//", remote)  # never a token from a remote URL
    tags = [t for t in _git(root, "tag", "--sort=-creatordate").splitlines() if t.strip()]
    return {"commits": len(rows), "contributors": len(people),
            "first": min(times) if times else None, "last": max(times) if times else None,
            "tags": len(tags), "latest_tag": tags[0] if tags else "", "remote": remote,
            "branch": _git(root, "rev-parse", "--abbrev-ref", "HEAD").strip()}


