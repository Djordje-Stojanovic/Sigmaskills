MAIN_NAMES = re.compile(r"(^|/)(main|__main__|cli|app|server|index|manage)\.(py|js|ts|mjs|go|rs|rb|java|kt|cs|php)$")


def entry_points(root: Path, files) -> dict:
    out = {"package_scripts": {}, "bins": {}, "console_scripts": {}, "make_targets": [], "dockerfiles": [], "mains": []}
    pkg = root / "package.json"
    if pkg.is_file():
        try:
            d = json.loads(pkg.read_text(encoding="utf-8"))
            out["package_scripts"] = {k: str(v)[:160] for k, v in (d.get("scripts") or {}).items()}
            b = d.get("bin")
            out["bins"] = {d.get("name", "bin"): b} if isinstance(b, str) else dict(b or {})
            if d.get("main"):
                out["mains"].append(d["main"])
        except (ValueError, OSError):
            pass
    pp = root / "pyproject.toml"
    if pp.is_file():
        text = pp.read_text(encoding="utf-8", errors="replace")
        m = re.search(r"(?ms)^\[project\.scripts\]\s*$(.*?)(?=^\[|\Z)", text) or \
            re.search(r"(?ms)^\[tool\.poetry\.scripts\]\s*$(.*?)(?=^\[|\Z)", text)
        if m:
            for k, v in re.findall(r'(?m)^\s*"?([\w.-]+)"?\s*=\s*"([^"]+)"', m.group(1)):
                out["console_scripts"][k] = v
    for mk in ("Makefile", "makefile", "justfile", "Justfile"):
        f = root / mk
        if f.is_file():
            targets = re.findall(r"(?m)^([A-Za-z0-9][\w.-]*)\s*:(?!=)", f.read_text(encoding="utf-8", errors="replace"))
            out["make_targets"] = sorted(set(t for t in targets if t not in (".PHONY",)))[:60]
    for rel, _, _ in files:
        low = rel.lower()
        if low.endswith("dockerfile") or "/dockerfile." in low or low.startswith("dockerfile.") or low.endswith("docker-compose.yml") or low.endswith("compose.yaml"):
            out["dockerfiles"].append(rel)
        elif MAIN_NAMES.search(low) and low.count("/") <= 3 and not re.search(r"(^|/)(tests?|examples?|fixtures?|docs?)/", low):
            out["mains"].append(rel)
    out["mains"] = sorted(set(out["mains"]), key=lambda r: (r.count("/"), r))[:20]
    out["dockerfiles"] = out["dockerfiles"][:20]
    return out


