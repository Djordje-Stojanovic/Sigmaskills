#!/usr/bin/env python3
"""SigmaTour helper: measure a repository and write the facts into the tour page.

  python sigmatour.py scan  REPO [--json] [--exclude PATTERN ...]
  python sigmatour.py build REPO [--out FILE] [--minutes N] [--exclude PATTERN ...]
  python sigmatour.py check FILE [--minutes N]
  python sigmatour.py selftest

scan   Reads REPO without writing to it and prints what a tour needs: the size (files, folders, code lines
       without blank and comment lines, doc lines, languages, the biggest files, the folder tree), the
       history (commits, contributors, first and last commit, tags), the entry points (package scripts and
       bins, console scripts, Makefile targets, Dockerfiles, main files), the tests and CI, and the README
       held against the repo: commands whose script or file does not exist, paths that do not exist,
       environment variables the code reads but no doc names, scripts and top folders the README never
       mentions, and TODO, FIXME and HACK notes. It also suggests a tour length (15, 30, 45 or 60 min).
build  Makes the tour page from the template when FILE is missing (default ./<repo name>-tour.html), then
       writes the scan into its data block. The page draws the numbers band, the folder explorer, the
       history band and the "README says, the repo shows" table from it. Run it again after a change.
check  Lists what is still wrong in a tour page: FILL left or no data block (exit 1); long paragraphs,
       chip-heavy text, terms without a meaning, too few figures, a trace with fewer than 4 steps, a
       length far from the target (fixes, exit 0).

Standard library only. Exit codes: 0 fine, 1 a check failed, 2 bad arguments.
"""
