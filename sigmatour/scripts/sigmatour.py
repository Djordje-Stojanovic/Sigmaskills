def _readme(root: Path):
    for name in ("README.md", "readme.md", "Readme.md", "README.rst", "README.txt", "README"):
        p = root / name
        if p.is_file():
            return name, p.read_text(encoding="utf-8", errors="replace")
    return "", ""


def _commands(readme: str):
    """Shell lines from the README's code blocks: `$ npm test`, `npm run build`, `python x.py`."""
    out = []
    for lang, body in FENCE_RX.findall(readme):
        if lang.lower() not in SHELL_LANGS:
            continue
        for line in body.splitlines():
            line = re.sub(r"^\s*(?:\$|>|PS [^>]*>|#)\s+", "", line).strip()
            if line and not line.startswith(("#", "//")) and len(line) < 200:
                out.append(line)
    return out


def check_command(root: Path, cmd: str, scripts: dict, targets: list):
    """(ok, why) for one README command, or None when the repo cannot tell (an outside tool)."""
    m = re.match(r"^(?:npm|pnpm|yarn|bun)\s+(?:run\s+|run-script\s+)?([\w:.-]+)", cmd)
    builtin = {"install", "i", "add", "ci", "init", "create", "dlx", "x", "exec", "link", "publish", "remove", "update",
               "upgrade", "outdated", "audit", "pack", "version", "login", "whoami", "global", "config", "cache"}
    if m and (" run" in cmd[:9] or m.group(1) not in builtin):
        name = m.group(1)
        return (name in scripts, f"package.json has {'a' if name in scripts else 'no'} script '{name}'")
    m = re.match(r"^(?:make|just)\s+([\w.-]+)", cmd)
    if m:
        return (m.group(1) in targets, f"{'a' if m.group(1) in targets else 'no'} target '{m.group(1)}' in the Makefile")
    m = re.match(r"^(?:python3?|py|node|bash|sh|pwsh|powershell(?:\.exe)?|deno run|bun run|ruby|go run)\s+(?:-[\w-]+\s+)*([\w./\\-]+\.\w+)", cmd)
    if m and not m.group(1).startswith("-"):
        rel = m.group(1).replace("\\", "/")
        return ((root / rel).exists(), f"{rel} {'exists' if (root / rel).exists() else 'is not in the repo'}")
    m = re.match(r"^\.{1,2}/([\w./-]+)", cmd)
    if m:
        rel = m.group(1)
        return ((root / rel).exists(), f"{rel} {'exists' if (root / rel).exists() else 'is not in the repo'}")
    return None


def readme_vs_repo(root: Path, files, entries) -> dict:
    name, readme = _readme(root)
    out = {"readme": name, "readme_lines": len(readme.splitlines()), "commands": [], "paths": [], "env_hidden": [],
           "env_documented": 0, "env_used": 0, "scripts_unmentioned": [], "folders_unmentioned": [], "notes": {},
           "note_files": [], "has": {}}
    docs_text, env_used, notes = [], {}, {}
    tests = ci = 0
    for rel, kind, data in files:
        low = rel.lower()
        if TEST_RX.search(rel):
            tests += 1
        if CI_RX.match(rel):
            ci += 1
        if kind == "docs" or low.startswith(".env") or low.endswith((".env.example", ".env.sample")):
            docs_text.append(data.decode("utf-8", errors="replace"))
        if kind == "code":
            text = data.decode("utf-8", errors="replace")
            for rx in ENV_RX:
                for var in rx.findall(text):
                    if var not in COMMON_ENV:
                        env_used.setdefault(var, rel)
            n = len(NOTE_RX.findall(data))
            if n:
                notes[rel] = n
                for word in NOTE_RX.findall(data):
                    w = word.decode()
                    out["notes"][w] = out["notes"].get(w, 0) + 1
    out["note_files"] = [{"path": p, "n": n} for p, n in sorted(notes.items(), key=lambda kv: -kv[1])[:8]]
    docs = "\n".join(docs_text)
    out["env_used"] = len(env_used)
    out["env_hidden"] = [{"name": v, "used_in": p} for v, p in sorted(env_used.items()) if v not in docs][:40]
    out["env_documented"] = out["env_used"] - len([1 for v in env_used if v not in docs])
    scripts, targets = entries["package_scripts"], entries["make_targets"]
    seen = set()
    for cmd in _commands(readme):
        r = check_command(root, cmd, scripts, targets)
        if r and cmd not in seen:
            seen.add(cmd)
            out["commands"].append({"cmd": cmd, "ok": r[0], "why": r[1]})
    for token in re.findall(r"`([^`\n]{2,120})`|\]\((?!https?:|#|mailto:)([^)\s#]+)", readme):
        p = (token[0] or token[1]).strip().rstrip("/")
        if not PATHISH.match(p) or "<" in p or p in seen:
            continue
        seen.add(p)
        out["paths"].append({"path": p, "ok": (root / p.lstrip("./")).exists()})
    out["paths"] = out["paths"][:40]
    out["scripts_unmentioned"] = [k for k in scripts if not re.search(r"(?<![\w-])" + re.escape(k) + r"(?![\w-])", readme)][:30]
    tops = sorted({rel.split("/", 1)[0] for rel, _, _ in files if "/" in rel})
    out["folders_unmentioned"] = [t for t in tops if not t.startswith(".") and t not in readme][:30]
    has = lambda *names: next((n for n in names if (root / n).exists()), "")
    out["has"] = {"tests": tests, "ci": ci, "license": has("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "LICENCE"),
                  "contributing": has("CONTRIBUTING.md", ".github/CONTRIBUTING.md"), "changelog": has("CHANGELOG.md", "CHANGES.md", "HISTORY.md"),
                  "docs": has("docs", "doc", "documentation"), "agents": has("AGENTS.md", "CLAUDE.md", ".cursorrules"),
                  "env_example": has(".env.example", ".env.sample", ".env.template", "example.env")}
    return out


def suggest_minutes(stats_: dict) -> int:
    code = stats_.get("code", 0)
    return 15 if code < 3000 else 30 if code < 20000 else 45 if code < 80000 else 60


def scan(root: Path, extra=()) -> dict:
    root = Path(root)
    files = list(_files(root, extra))
    st = stats(root, extra)
    entries = entry_points(root, files)
    return {"name": root.resolve().name, "stats": st, "history": history(root), "entries": entries,
            "readme": readme_vs_repo(root, files, entries), "minutes": suggest_minutes(st)}


def cmd_scan(root: Path, as_json: bool, extra) -> int:
    d = scan(root, extra)
    if as_json:
        print(json.dumps(d, indent=1, default=str))
        return 0
    s, h, e, r = d["stats"], d["history"], d["entries"], d["readme"]
    print(f"{d['name']}: {s['files']:,} files, {s['folders']:,} folders, {s['code']:,} code lines, {s['docs']:,} doc lines")
    print("languages: " + ", ".join(f"{l['name']} {l['code']:,}" for l in s["langs"][:6]))
    if h:
        print(f"history: {h['commits']:,} commits by {h['contributors']} people, {h['tags']} tags, branch {h['branch']}")
    print(f"entry points: {len(e['package_scripts'])} package scripts, {len(e['bins'])} bins, {len(e['console_scripts'])} console scripts, "
          f"{len(e['make_targets'])} make targets, mains: {', '.join(e['mains'][:6]) or 'none'}")
    print(f"README ({r['readme'] or 'none'}, {r['readme_lines']} lines): {sum(c['ok'] for c in r['commands'])}/{len(r['commands'])} commands "
          f"check out, {sum(p['ok'] for p in r['paths'])}/{len(r['paths'])} paths exist")
    print(f"hidden: {len(r['env_hidden'])} env vars used but never documented; scripts not in the README: "
          f"{', '.join(r['scripts_unmentioned'][:8]) or 'none'}; folders not in the README: {', '.join(r['folders_unmentioned'][:8]) or 'none'}")
    print(f"notes in code: {r['notes'] or 'none'}; tests: {r['has']['tests']} files; CI: {r['has']['ci']} files")
    print(f"suggested tour: {d['minutes']} minutes")
    return 0


# ---------- build: the tour page ----------

DATA_RX = re.compile(r'(<script type="application/json" id="sigmatour-data">)(.*?)(</script>)', re.S)
TEMPLATE = Path(__file__).resolve().parent.parent / "assets" / "tour-template.html"


def cmd_build(root: Path, out: Path | None, minutes: int | None, extra) -> int:
    out = out or Path.cwd() / f"{root.resolve().name}-tour.html"
    if not out.exists():
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(TEMPLATE, out)
        print(f"new tour from the template: {out}")
    with open(out, encoding="utf-8", newline="") as fh:
        html = fh.read()
    if not DATA_RX.search(html):
        print("the page has no sigmatour-data block; start again from assets/tour-template.html", file=sys.stderr)
        return 1
    data = scan(root, extra)
    if minutes:
        data["minutes"] = minutes
    blob = json.dumps(data, separators=(",", ":"), default=str).replace("</", "<\\/")
    with open(out, "w", encoding="utf-8", newline="") as fh:
        fh.write(DATA_RX.sub(lambda m: m.group(1) + blob + m.group(3), html, count=1))
    s = data["stats"]
    print(f"wrote repo data into {out}: {s['files']:,} files, {s['code']:,} code lines, target {data['minutes']} min")
    return 0


# ---------- check ----------

def tour_check(html: str, minutes: int | None = None) -> tuple[list, list]:
    """(blocking, fixes). A check is a fix list, not a taste judge."""
    blocking, fixes = [], []
    for m in re.finditer(r"\bFILL\b", html):
        blocking.append(f"line {html.count(chr(10), 0, m.start()) + 1}: FILL left")
    m = DATA_RX.search(html)
    if not m or not m.group(2).strip().startswith("{"):
        blocking.append("no repo data: run `sigmatour.py build <repo> --out <page>`")
    elif minutes is None:
        try:
            minutes = json.loads(m.group(2).replace("<\\/", "</")).get("minutes")
        except ValueError:
            pass
    figures = len(re.findall(r"<figure\b", html))
    if figures < 6:
        fixes.append(f"{figures} figures; a tour wants 6 or more (map, numbers, history, trace, examples, README table)")
    steps = len(re.findall(r'<li[^>]*class="[^"]*\bstep\b', html))
    if steps < 4:
        fixes.append(f"the trace has {steps} steps; follow one real request or command through at least 4 files")
    total = sum(int(x) for x in re.findall(r'class="stop-sec"[^>]*data-min="(\d+)"', html))
    if minutes and total and not (0.75 * minutes <= total <= 1.25 * minutes):
        fixes.append(f"the stops add up to {total} min; the target is {minutes} min (add or cut deep dives)")
    body = re.sub(r"<script.*?</script>|<style.*?</style>|<!--.*?-->", "", html, flags=re.S)
    for pm in re.finditer(r"<p\b[^>]*>(.*?)</p>", body, re.S):
        inner = pm.group(1)
        text = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", inner)).strip()
        words = len(text.split())
        sentences = len(re.findall(r"[.!?](?:\s|$)", text))
        line = body.count("\n", 0, pm.start()) + 1
        if words > 70 or sentences > 3:
            fixes.append(f"line ~{line}: {words} words, {sentences} sentences; split it (3 sentences, 70 words at most)")
        if len(re.findall(r"<code\b", inner)) > 3:
            fixes.append(f"line ~{line}: more than 3 inline code chips; move commands into a code block")
    for tm in re.finditer(r'<(?:span|abbr|dfn)[^>]*class="term"[^>]*>', body):
        if "data-def=" not in tm.group(0):
            fixes.append(f"term without data-def: {tm.group(0)[:60]}")
    return blocking, fixes


def cmd_check(page: Path, minutes: int | None) -> int:
    if not page.is_file():
        print(f"no tour at {page}", file=sys.stderr)
        return 1
    blocking, fixes = tour_check(page.read_text(encoding="utf-8", errors="replace"), minutes)
    for b in blocking:
        print("BLOCK " + b)
    for f in fixes:
        print("FIX   " + f)
    print(f"tour check: {len(blocking)} blocking, {len(fixes)} fixes")
    return 1 if blocking else 0


# ---------- selftest ----------

def cmd_selftest() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="sigmatour-"))
    try:
        repo = tmp / "demo"
        (repo / "src").mkdir(parents=True)
        (repo / "node_modules" / "x").mkdir(parents=True)
        (repo / "package.json").write_text(json.dumps({"name": "demo", "scripts": {"build": "node src/main.js", "lint": "x"}}), encoding="utf-8")
        (repo / "src" / "main.js").write_text("// entry\nconst k = process.env.DEMO_TOKEN;\n// TODO: retry\nconsole.log(k)\n", encoding="utf-8")
        (repo / "README.md").write_text("# Demo\n\n```bash\nnpm run build\nnpm run deploy\npython tools/gen.py\n```\n\nSee `src/main.js` and `docs/guide.md`.\n", encoding="utf-8")
        d = scan(repo)
        cmds = {c["cmd"]: c["ok"] for c in d["readme"]["commands"]}
        assert cmds == {"npm run build": True, "npm run deploy": False, "python tools/gen.py": False}, cmds
        paths = {p["path"]: p["ok"] for p in d["readme"]["paths"]}
        assert paths == {"src/main.js": True, "docs/guide.md": False}, paths
        assert [e["name"] for e in d["readme"]["env_hidden"]] == ["DEMO_TOKEN"]
        assert d["readme"]["scripts_unmentioned"] == ["lint"] and d["readme"]["notes"] == {"TODO": 1}
        assert "src/main.js" in d["entries"]["mains"] and d["stats"]["code"] == 2 and d["minutes"] == 15
        page = tmp / "demo-tour.html"
        assert cmd_build(repo, page, None, ()) == 0 and cmd_build(repo, page, 30, ()) == 0
        blocking, _ = tour_check(page.read_text(encoding="utf-8"))
        assert any("FILL left" in b for b in blocking) and not any("no repo data" in b for b in blocking)
        print("selftest ok")
        return 0
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("scan")
    s.add_argument("repo")
    s.add_argument("--json", action="store_true")
    s.add_argument("--exclude", action="append", default=[], help="another folder name or glob to leave out")
    b = sub.add_parser("build")
    b.add_argument("repo")
    b.add_argument("--out", help="the tour page (default ./<repo name>-tour.html)")
    b.add_argument("--minutes", type=int, help="the tour length the user asked for (default: suggested from the size)")
    b.add_argument("--exclude", action="append", default=[], help="another folder name or glob to leave out")
    c = sub.add_parser("check")
    c.add_argument("page")
    c.add_argument("--minutes", type=int, help="the target length (default: the one in the page's data block)")
    sub.add_parser("selftest")
    a = ap.parse_args(argv)
    if a.cmd == "selftest":
        return cmd_selftest()
    if a.cmd == "check":
        return cmd_check(Path(a.page), a.minutes)
    root = Path(a.repo)
    if not root.is_dir():
        print(f"not a folder: {root}", file=sys.stderr)
        return 2
    if a.cmd == "scan":
        return cmd_scan(root, a.json, a.exclude)
    return cmd_build(root, Path(a.out) if a.out else None, a.minutes, a.exclude)


if __name__ == "__main__":
    sys.exit(main())
